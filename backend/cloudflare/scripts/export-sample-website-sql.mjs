// Builds backend/cloudflare/seeds/sample-website.sql from backend/shared/sampleWebsite.js
// (LANDING_V1 §4). LOCAL D1 ONLY: apply with `npm run d1:seed:sample:local`. Never add this
// file to migrations, seed.sql or CI, and never run it with --remote.
//
// The SQL is idempotent and mirrors backend/scripts/seed-sample-website.mjs:
// - FAQs, reviews and client logos are upserted by their fixed `sample-` ids, except records an
//   admin has saved since (sample: false), which are kept;
// - existing portfolio records (by id) get the sample case-study fields and sample: true, unless
//   an admin has saved them since;
// - the website, financing and calculator settings sections are set only while they are
//   missing, empty or still sample content (isSeedableSection).
import { mkdir, writeFile } from "fs/promises";
import { dirname, resolve } from "path";
import { fileURLToPath, pathToFileURL } from "url";
import {
  SAMPLE_COLLECTIONS,
  SAMPLE_PORTFOLIO,
  SAMPLE_SEEDED_AT,
  SAMPLE_SETTINGS,
} from "../../shared/sampleWebsite.js";
import { SETTINGS_ID } from "../../shared/settings.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outputPath = resolve(__dirname, "../seeds/sample-website.sql");

const sql = (value) => (value === null || value === undefined ? "NULL" : `'${String(value).replaceAll("'", "''")}'`);

const recordSql = (collection, item) =>
  [
    "INSERT INTO records (id, collection, slug, data, is_active, sort_order, created_at, updated_at)",
    `  VALUES (${sql(item.id)}, ${sql(collection)}, NULL, ${sql(JSON.stringify(item))}, ${item.isActive === false ? 0 : 1}, ${Number(item.sortOrder) || 0}, ${sql(item.createdAt)}, ${sql(item.updatedAt)})`,
    "  ON CONFLICT (id) DO UPDATE SET data = json_set(excluded.data, '$.createdAt', json_extract(records.data, '$.createdAt')),",
    "    is_active = excluded.is_active, sort_order = excluded.sort_order, updated_at = excluded.updated_at",
    `  WHERE records.collection = ${sql(collection)} AND json_extract(records.data, '$.sample') = 1;`,
  ].join("\n");

const portfolioSql = ({ id, category, summary, location, system }) =>
  [
    "UPDATE records SET data = json_set(data,",
    `    '$.category', ${sql(category)}, '$.summary', ${sql(summary)}, '$.location', ${sql(location)}, '$.system', ${sql(system)},`,
    "    '$.sample', json('true'))",
    `  WHERE collection = 'portfolio' AND id = ${sql(id)} AND COALESCE(json_extract(data, '$.sample'), 1) = 1;`,
  ].join("\n");

// SQL mirror of isSeedableSection (backend/shared/sampleWebsite.js).
const SEEDABLE = {
  website:
    "COALESCE(json_array_length(data, '$.website.stats'), 0) = 0 AND json_extract(data, '$.website.whatsappNumber') IS NULL AND json_extract(data, '$.website.businessHours') IS NULL",
  financing:
    "COALESCE(json_extract(data, '$.financing.enabled'), 0) != 1 AND COALESCE(json_array_length(data, '$.financing.termsMonths'), 0) = 0 AND json_extract(data, '$.financing.depositPercent') IS NULL",
  calculator:
    "COALESCE(json_extract(data, '$.calculator.enabled'), 0) != 1 AND COALESCE(json_array_length(data, '$.calculator.appliances'), 0) = 0",
};

const settingsSql = () => {
  const document = { id: SETTINGS_ID, updatedAt: SAMPLE_SEEDED_AT, updatedBy: null };
  return [
    "-- Settings: create the global document when missing, then set each sample section only while it is",
    "-- missing, empty or still sample content (real, saved sections are kept).",
    "INSERT INTO records (id, collection, slug, data, is_active, sort_order, created_at, updated_at)",
    `  VALUES (${sql(SETTINGS_ID)}, 'settings', NULL, ${sql(JSON.stringify(document))}, 1, 0, ${sql(SAMPLE_SEEDED_AT)}, ${sql(SAMPLE_SEEDED_AT)})`,
    "  ON CONFLICT (id) DO NOTHING;",
    ...Object.entries(SAMPLE_SETTINGS).map(([section, value]) =>
      [
        `UPDATE records SET data = json_set(data, '$.${section}', json(${sql(JSON.stringify(value))}))`,
        `  WHERE collection = 'settings' AND id = ${sql(SETTINGS_ID)} AND (`,
        `    json_type(data, '$.${section}') IS NOT 'object'`,
        `    OR json_extract(data, '$.${section}.sample') = 1`,
        `    OR (${SEEDABLE[section]})`,
        "  );",
      ].join("\n")
    ),
  ].join("\n");
};

/** The full SQL file content. */
export const buildSampleWebsiteSql = () =>
  [
    "-- LOCAL DEVELOPMENT ONLY. NEVER run this file with --remote, and never add it to migrations, seed.sql or CI.",
    "-- Sample website content (LANDING_V1 §4); every record and section is sample: true and must be replaced before launch.",
    "-- Generated by backend/cloudflare/scripts/export-sample-website-sql.mjs from backend/shared/sampleWebsite.js.",
    "-- Apply with: npm run d1:seed:sample:local (wrangler d1 execute juwon-electric --local --file seeds/sample-website.sql)",
    "",
    ...Object.entries(SAMPLE_COLLECTIONS).flatMap(([collection, items]) => [
      `-- ${collection}`,
      ...items.map((item) => recordSql(collection, item)),
      "",
    ]),
    "-- portfolio case-study fields (existing records, by id)",
    ...SAMPLE_PORTFOLIO.map(portfolioSql),
    "",
    settingsSql(),
    "",
  ].join("\n");

export const SAMPLE_WEBSITE_SQL_PATH = outputPath;

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, buildSampleWebsiteSql());
  console.log(`Sample website SQL written to ${outputPath}`);
}
