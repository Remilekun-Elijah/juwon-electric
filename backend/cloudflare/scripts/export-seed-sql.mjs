// Builds backend/cloudflare/seed.sql for the public catalog only
// (packages, services, customerSegments, portfolio). It never reads
// backend/data/db.json, so admins, contacts, orders, newsletters, carts and
// password resets can't end up in the seed file.
//
// The source is the same default catalog the Express store uses
// (frontend/src/utils/plans.json + backend/data/seed.js). Record ids and
// timestamps come from backend/data/catalog-ids.json so that reseeding D1
// (INSERT OR REPLACE) updates the existing rows instead of adding duplicates.
// Rows missing from the map get a new uuid, which is written back to the map.
import { randomUUID } from "crypto";
import { readFile, writeFile, mkdir } from "fs/promises";
import { dirname, resolve } from "path";
import { fileURLToPath } from "url";
import { buildDefaultCatalog } from "../../services/store.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const backendRoot = resolve(__dirname, "../..");
const idMapPath = resolve(backendRoot, "data/catalog-ids.json");
const outputPath = resolve(__dirname, "../seed.sql");

const collections = ["packages", "services", "customerSegments", "portfolio"];

const sqlString = (value) =>
  `'${String(value ?? "").replaceAll("'", "''")}'`;

const rowSql = (collection, item, index) => {
  const data = { ...item, id: String(item.id) };

  return [
    "INSERT OR REPLACE INTO records",
    "(id, collection, slug, data, is_active, sort_order, created_at, updated_at)",
    "VALUES",
    `(${sqlString(data.id)}, ${sqlString(collection)}, ${sqlString(data.slug)}, ${sqlString(JSON.stringify(data))}, ${data.isActive === false ? 0 : 1}, ${Number(data.sortOrder || index + 1)}, ${sqlString(data.createdAt)}, ${sqlString(data.updatedAt)});`,
  ].join(" ");
};

// packages: public legacyId; others: slug, with "#N" for the Nth repeated slug.
const recordKeys = (collection, items) => {
  const seen = new Map();
  const keys = items.map((item) => {
    if (collection === "packages") return String(item.legacyId);
    const count = (seen.get(item.slug) || 0) + 1;
    seen.set(item.slug, count);
    return count > 1 ? `${item.slug}#${count}` : item.slug;
  });

  const duplicates = keys.filter((key, index) => keys.indexOf(key) !== index);
  if (duplicates.length) {
    throw new Error(
      `Duplicate ${collection === "packages" ? "package ids" : `${collection} keys`}: ${[
        ...new Set(duplicates),
      ].join(", ")}`
    );
  }
  return keys;
};

const idMap = JSON.parse(await readFile(idMapPath, "utf8"));
idMap.collections ||= {};
const catalog = await buildDefaultCatalog({ strict: true });
const createdAt = new Date().toISOString();
let mapChanged = false;

const rows = collections.flatMap((collection) => {
  const items = catalog[collection] || [];
  const map = (idMap.collections[collection] ||= {});
  const keys = recordKeys(collection, items);

  for (const staleKey of Object.keys(map).filter((key) => !keys.includes(key))) {
    console.warn(`Warning: ${collection} "${staleKey}" is in catalog-ids.json but not in the catalog source; its D1 row is left untouched.`);
  }

  return items.map((item, index) => {
    const key = keys[index];
    if (!map[key]) {
      map[key] = { id: randomUUID(), createdAt, updatedAt: createdAt };
      mapChanged = true;
      console.log(`New ${collection} record "${key}" -> ${map[key].id}`);
    }
    const { id, createdAt: rowCreatedAt, updatedAt } = map[key];
    return rowSql(collection, { ...item, id, createdAt: rowCreatedAt, updatedAt }, index);
  });
});

const statements = [
  "-- Generated by backend/cloudflare/scripts/export-seed-sql.mjs from frontend/src/utils/plans.json + backend/data/seed.js (ids: backend/data/catalog-ids.json)",
  "-- Catalog only (packages, services, customerSegments, portfolio); never contains admins or customer data.",
  "-- Apply with: wrangler d1 execute juwon-electric --remote --file backend/cloudflare/seed.sql",
  ...rows,
  "",
];

if (mapChanged) {
  await writeFile(idMapPath, `${JSON.stringify(idMap, null, 2)}\n`);
  console.log(`Updated ${idMapPath}`);
}
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, statements.join("\n"));
console.log(`Seed SQL written to ${outputPath}`);
